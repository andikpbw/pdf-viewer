  /// Adds a new page to the document using a [PdfPageBuilder] callback.
  void addPage({
    double width = 595.28,
    double height = 841.89,
    String? bookmarkTitle,
    required void Function(PdfPageBuilder page) build,
  }) {
    final int pageNum = _pages.length + 1;
    final PdfPageBuilder pageBuilder = PdfPageBuilder(
      pageNumber: pageNum,
      width: width,
      height: height,
    );
    build(pageBuilder);
    _pages.add(
      _BuiltPageRecord(
        pageData: pageBuilder.toPageData(),
        contentStream: pageBuilder.toPdfContentStream(),
        bookmarkTitle: bookmarkTitle,
      ),
    );
  }

  /// Builds the [PdfDocument] along with its serialized `%PDF-1.7` byte payload.
  PdfDocument build({bool compressStreams = false}) {
    final Uint8List pdfBytes = toPdfBytes(compressStreams: compressStreams);
    final List<PdfPageData> pageList =
        _pages.map((_BuiltPageRecord r) => r.pageData).toList(growable: false);
    final List<PdfBookmark> bookmarks = <PdfBookmark>[];

    for (int i = 0; i < _pages.length; i++) {
      final String? bmTitle = _pages[i].bookmarkTitle;
      if (bmTitle != null && bmTitle.isNotEmpty) {
        bookmarks.add(
          PdfBookmark(
            id: 'bm_${i + 1}',
            title: bmTitle,
            pageNumber: i + 1,
          ),
        );
      }
    }

    return PdfDocument(
      pages: pageList,
      bookmarks: bookmarks,
      rawBytes: pdfBytes,
      metadata: PdfMetadata(
        title: title,
        author: author,
        subject: subject,
        keywords: keywords,
        creator: creator,
        producer: producer,
        creationDate: DateTime.utc(2026, 1, 1),
        modificationDate: DateTime.utc(2026, 1, 1),
        version: '1.7',
        fileSizeInBytes: pdfBytes.length,
      ),
    );
  }

  /// Serializes the built document into a valid `%PDF-1.7` byte buffer.
  Uint8List toPdfBytes({bool compressStreams = false}) {
    final BytesBuilder out = BytesBuilder(copy: false);
    final List<int> xrefOffsets = <int>[0]; // Object 0 is free

    void writeAscii(String text) {
      out.add(latin1.encode(text));
    }

    int startObject(int id) {
      final int offset = out.length;
      while (xrefOffsets.length <= id) {
        xrefOffsets.add(0);
      }
      xrefOffsets[id] = offset;
      writeAscii('$id 0 obj\n');
      return offset;
    }

    void endObject() {
      writeAscii('endobj\n');
    }

    writeAscii('%PDF-1.7\n');

    final int pageCount = _pages.length;
    const int firstPageObjId = 7;

    // Collect bookmarked page indices.
    final List<int> bookmarkedIndices = <int>[];
    for (int i = 0; i < _pages.length; i++) {
      final String? bm = _pages[i].bookmarkTitle;
      if (bm != null && bm.isNotEmpty) {
        bookmarkedIndices.add(i);
      }
    }
    final int outlinesRootId = firstPageObjId + pageCount * 2;
    final bool hasOutlines = bookmarkedIndices.isNotEmpty;

    startObject(1);
    writeAscii(
      hasOutlines
          ? '<< /Type /Catalog /Pages 2 0 R /Outlines $outlinesRootId 0 R >>\n'
          : '<< /Type /Catalog /Pages 2 0 R >>\n',
    );
    endObject();

    final List<String> kidsRefs = <String>[];
    for (int i = 0; i < pageCount; i++) {
      final int pageObjId = firstPageObjId + i * 2;
      kidsRefs.add('$pageObjId 0 R');
    }

    startObject(2);
    writeAscii(
      '<< /Type /Pages /Kids [ ${kidsRefs.join(' ')} ] /Count $pageCount >>\n',
    );
    endObject();

    startObject(3);
    writeAscii(
      '<< /Title ${_encodePdfTextOperand(title)} '
      '/Author ${_encodePdfTextOperand(author)} '
      '/Subject ${_encodePdfTextOperand(subject)} '
      '/Keywords ${_encodePdfTextOperand(keywords)} '
      '/Creator ${_encodePdfTextOperand(creator)} '
      '/Producer ${_encodePdfTextOperand(producer)} '
      '/CreationDate (D:20260101000000Z) >>\n',
    );
    endObject();

    startObject(4);
    writeAscii(
      '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\n',
    );
    endObject();

    startObject(5);
    writeAscii(
      '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>\n',
    );
    endObject();

    startObject(6);
    writeAscii(
      '<< /Type /Font /Subtype /Type1 /BaseFont /Courier >>\n',
    );
    endObject();

    for (int i = 0; i < pageCount; i++) {
      final _BuiltPageRecord rec = _pages[i];
      final int pageObjId = firstPageObjId + i * 2;
      final int contentObjId = pageObjId + 1;
      final String wStr = rec.pageData.width.toStringAsFixed(2);
      final String hStr = rec.pageData.height.toStringAsFixed(2);

      startObject(pageObjId);
      writeAscii(
        '<< /Type /Page /Parent 2 0 R '
        '/MediaBox [ 0 0 $wStr $hStr ] '
        '/Resources << /Font << /F1 4 0 R /F2 5 0 R /F4 6 0 R >> >> '
        '/Contents $contentObjId 0 R >>\n',
      );
      endObject();

      final Uint8List rawStreamBytes =
          Uint8List.fromList(latin1.encode(rec.contentStream));
      final Uint8List payload = compressStreams
          ? ZlibDecoder.encodeZlibStored(rawStreamBytes)
          : rawStreamBytes;
      final String filterEntry = compressStreams ? ' /Filter /FlateDecode' : '';

      startObject(contentObjId);
      writeAscii('<< /Length ${payload.length}$filterEntry >>\nstream\n');
      out.add(payload);
      writeAscii('\nendstream\n');
      endObject();
    }

    // Standard PDF /Outlines tree for universal viewer compatibility.
    if (hasOutlines) {
      final int firstItemId = outlinesRootId + 1;
      final int lastItemId = outlinesRootId + bookmarkedIndices.length;

      startObject(outlinesRootId);
      writeAscii(
        '<< /Type /Outlines /First $firstItemId 0 R '
        '/Last $lastItemId 0 R /Count ${bookmarkedIndices.length} >>\n',
      );
      endObject();

      for (int idx = 0; idx < bookmarkedIndices.length; idx++) {
        final int pageIndex = bookmarkedIndices[idx];
        final int itemObjId = firstItemId + idx;
        final int targetPageObjId = firstPageObjId + pageIndex * 2;
        final String bm = _pages[pageIndex].bookmarkTitle!;
        final String prevPart = idx > 0 ? ' /Prev ${itemObjId - 1} 0 R' : '';
        final String nextPart = idx + 1 < bookmarkedIndices.length
            ? ' /Next ${itemObjId + 1} 0 R'
            : '';

        startObject(itemObjId);
        writeAscii(
          '<< /Title ${_encodePdfTextOperand(bm)} '
          '/Parent $outlinesRootId 0 R$prevPart$nextPart '
          '/Dest [ $targetPageObjId 0 R /Fit ] '
          '/PageNumber ${pageIndex + 1} >>\n',
        );
        endObject();
      }
    }

    final int xrefStart = out.length;
    final int totalObjects = xrefOffsets.length;
    writeAscii('xref\n0 $totalObjects\n');
    writeAscii('0000000000 65535 f \n');
    for (int id = 1; id < totalObjects; id++) {
      final String padded = xrefOffsets[id].toString().padLeft(10, '0');
      writeAscii('$padded 00000 n \n');
    }
    writeAscii(
      'trailer\n<< /Size $totalObjects /Root 1 0 R /Info 3 0 R >>\n'
      'startxref\n$xrefStart\n%%EOF\n',
    );

    return out.takeBytes();
  }

  static String _encodePdfTextOperand(String input) {
    final bool hasNonAscii = input.codeUnits.any((int cu) => cu > 127);
    if (!hasNonAscii) {
      final String escaped = input
          .replaceAll(r'\', r'\\')
          .replaceAll('(', r'\(')
          .replaceAll(')', r'\)');
      return '($escaped)';
    }
    final StringBuffer hex = StringBuffer('FEFF');
    for (final int cu in input.codeUnits) {
      final int hi = (cu >> 8) & 0xFF;
      final int lo = cu & 0xFF;
      hex.write(hi.toRadixString(16).padLeft(2, '0').toUpperCase());
      hex.write(lo.toRadixString(16).padLeft(2, '0').toUpperCase());
    }
    return '<$hex>';
  }
}

/// Page layout builder used inside [PdfDocumentBuilder.addPage].
class PdfPageBuilder {
  /// Creates a [PdfPageBuilder] for the given [pageNumber] and dimensions.
  PdfPageBuilder({
    required this.pageNumber,
    this.width = 595.28,
    this.height = 841.89,
    this.margin = 44.0,
  }) : _cursorY = margin;

  /// 1-based page number.
  final int pageNumber;

  /// Page width in points.
  final double width;

  /// Page height in points.
  final double height;

  /// Horizontal and vertical page margin in points.
  final double margin;

  double _cursorY;
  final List<PdfGraphicElement> _elements = <PdfGraphicElement>[];
  final StringBuffer _stream = StringBuffer();

  double get _contentWidth => width - margin * 2;
  double _toPdfY(double topY) => height - topY;

  /// Adds vertical whitespace of [points] height.
  void addSpacer([double points = 12.0]) {
    _cursorY += points;
  }

  /// Adds a full-width top banner header to the page.
  void addBannerHeader({
    required String title,
    String? subtitle,
    Color backgroundColor = const Color(0xFF0F172A),
    Color accentColor = const Color(0xFF38BDF8),
    Color textColor = const Color(0xFFFFFFFF),
  }) {
    final Rect bannerRect = Rect.fromLTWH(margin, _cursorY, _contentWidth, 70);
    _addRect(bannerRect, fillColor: backgroundColor, cornerRadius: 10);

    final Rect stripRect = Rect.fromLTWH(margin, _cursorY, 6, 70);
    _addRect(stripRect, fillColor: accentColor, cornerRadius: 3);

    _addTextLine(
      text: title,
      left: margin + 20,
      top: _cursorY + 14,
      fontSize: 17.5,
      color: textColor,
      isBold: true,
    );
    if (subtitle != null && subtitle.isNotEmpty) {
      _addTextLine(
        text: subtitle,
        left: margin + 20,
        top: _cursorY + 42,
        fontSize: 9.8,
        color: accentColor,
      );
    }
    _cursorY += 78;
  }

  /// Adds a row of modern KPI metric summary cards across the page width.
  void addMetricCards(
    Map<String, String> metrics, {
    Color accentColor = const Color(0xFF2563EB),
    Color cardBackgroundColor = const Color(0xFFF8FAFC),
  }) {
    if (metrics.isEmpty) {
      return;
    }
    final List<MapEntry<String, String>> entries = metrics.entries.toList();
    const double gap = 10.0;
    final double cardWidth =
        (_contentWidth - gap * (entries.length - 1)) / entries.length;
    const double cardHeight = 52.0;

    for (int i = 0; i < entries.length; i++) {
      final double left = margin + i * (cardWidth + gap);
      _addRect(
        Rect.fromLTWH(left, _cursorY, cardWidth, cardHeight),
        fillColor: cardBackgroundColor,
        strokeColor: const Color(0xFFE2E8F0),
        strokeWidth: 0.8,
        cornerRadius: 7,
      );
      _addRect(
        Rect.fromLTWH(left + 10, _cursorY + 8, 22, 3),
        fillColor: accentColor,
        cornerRadius: 1.5,
      );
      _addTextLine(
        text: entries[i].value,
        left: left + 10,
        top: _cursorY + 17,
        fontSize: 11.4,
        color: const Color(0xFF0F172A),
        isBold: true,
      );
      _addTextLine(
        text: entries[i].key,
        left: left + 10,
        top: _cursorY + 34,
        fontSize: 8.3,
        color: const Color(0xFF64748B),
      );
    }
    _cursorY += cardHeight + 8;
  }

  /// Adds a section heading (`level` 1, 2, or 3).
  void addHeading(
    String text, {
    int level = 1,
    Color color = const Color(0xFF0F172A),
  }) {
    final double fontSize = switch (level) {
      1 => 16.5,
      2 => 13.0,
      _ => 11.2,
    };
    _cursorY += level == 1 ? 6.0 : 4.0;
    _addTextLine(
      text: text,
      left: margin,
      top: _cursorY,
      fontSize: fontSize,
      color: color,
      isBold: true,
    );
    _cursorY += fontSize * 1.42;
    if (level == 1) {
      addDivider(color: const Color(0xFFE2E8F0), thickness: 1.2);
      _cursorY += 6;
    }
  }

  /// Adds a word-wrapped paragraph of body text.
  void addParagraph(
    String text, {
    double fontSize = 10.6,
    Color color = const Color(0xFF334155),
  }) {
    final List<String> lines = _wrapText(text, _contentWidth, fontSize);
    for (final String line in lines) {
      _addTextLine(
        text: line,
        left: margin,
        top: _cursorY,
        fontSize: fontSize,
        color: color,
      );
      _cursorY += fontSize * 1.45;
    }
    _cursorY += 4;
  }

  /// Adds a styled bulleted list of concise points.
  void addBulletList(
    List<String> items, {
    double fontSize = 10.2,
    Color bulletColor = const Color(0xFF2563EB),
    Color textColor = const Color(0xFF334155),
  }) {
    for (final String item in items) {
      final List<String> wrapped =
          _wrapText(item, _contentWidth - 18, fontSize);
      for (int i = 0; i < wrapped.length; i++) {
        if (i == 0) {
          _addRect(
            Rect.fromLTWH(margin + 3, _cursorY + 4.5, 5, 5),
            fillColor: bulletColor,
            cornerRadius: 2.5,
          );
        }
        _addTextLine(
          text: wrapped[i],
          left: margin + 15,
          top: _cursorY,
          fontSize: fontSize,
          color: textColor,
        );
        _cursorY += fontSize * 1.45;
      }
      _cursorY += 3;
    }
    _cursorY += 2;
  }

  /// Adds a dark editor-style monospace code snippet block.
  void addCodeBlock({
    required String code,
    String? title,
    Color backgroundColor = const Color(0xFF0F172A),
    Color textColor = const Color(0xFFE2E8F0),
    Color accentColor = const Color(0xFF38BDF8),
  }) {
    final List<String> codeLines = code.split('\n');
    final double headerH = (title != null && title.isNotEmpty) ? 24.0 : 0.0;
    final double boxHeight = headerH + 16.0 + codeLines.length * 14.5 + 8.0;

    _addRect(
      Rect.fromLTWH(margin, _cursorY, _contentWidth, boxHeight),
      fillColor: backgroundColor,
      strokeColor: const Color(0xFF1E293B),
      strokeWidth: 1.0,
      cornerRadius: 8,
    );

    if (headerH > 0) {
      _addRect(
        Rect.fromLTWH(margin, _cursorY, _contentWidth, headerH),
        fillColor: const Color(0xFF1E293B),
        cornerRadius: 8,
      );
      _addRect(
        Rect.fromLTWH(margin + 12, _cursorY + 9, 6, 6),
        fillColor: const Color(0xFFEF4444),
        cornerRadius: 3,
      );
      _addRect(
        Rect.fromLTWH(margin + 22, _cursorY + 9, 6, 6),
        fillColor: const Color(0xFFF59E0B),
        cornerRadius: 3,
      );
      _addRect(
        Rect.fromLTWH(margin + 32, _cursorY + 9, 6, 6),
        fillColor: const Color(0xFF22C55E),
        cornerRadius: 3,
      );
      _addTextLine(
        text: title!,
        left: margin + 48,
        top: _cursorY + 6,
        fontSize: 9.0,
        color: accentColor,
        isBold: true,
      );
    }

    double lineY = _cursorY + headerH + 10.0;
    for (final String line in codeLines) {
      _addTextLine(
        text: line.isEmpty ? ' ' : line,
        left: margin + 14,
        top: lineY,
        fontSize: 9.6,
        color: textColor,
        isMonospace: true,
      );
      lineY += 14.5;
    }

    _cursorY += boxHeight + 10;
  }

  /// Adds a highlighted callout box with a left accent border.
  void addCalloutBox({
    required String title,
    required String body,
    Color accentColor = const Color(0xFF2563EB),
    Color backgroundColor = const Color(0xFFEFF6FF),
  }) {
    final List<String> bodyLines = _wrapText(body, _contentWidth - 32, 10.0);
    final double boxHeight = 32.0 + bodyLines.length * 14.5 + 10.0;

    final Rect boxRect =
        Rect.fromLTWH(margin, _cursorY, _contentWidth, boxHeight);
    _addRect(
      boxRect,
      fillColor: backgroundColor,
      strokeColor: accentColor.withAlpha(70),
      cornerRadius: 7,
    );
    _addRect(
      Rect.fromLTWH(margin, _cursorY, 5, boxHeight),
      fillColor: accentColor,
      cornerRadius: 2.5,
    );

    _addTextLine(
      text: title,
      left: margin + 16,
      top: _cursorY + 9,
      fontSize: 11.2,
      color: accentColor,
      isBold: true,
    );

    double lineY = _cursorY + 28;
    for (final String line in bodyLines) {
      _addTextLine(
        text: line,
        left: margin + 16,
        top: lineY,
        fontSize: 10.0,
        color: const Color(0xFF1E293B),
      );
      lineY += 14.5;
    }

    _cursorY += boxHeight + 8;
  }

  /// Adds a two-column key-value summary grid.
  void addKeyValueGrid(Map<String, String> items) {
    final List<MapEntry<String, String>> entries = items.entries.toList();
    const double rowHeight = 23.0;
    for (int i = 0; i < entries.length; i++) {
      final MapEntry<String, String> entry = entries[i];
      final Color rowBg =
          i.isEven ? const Color(0xFFF8FAFC) : const Color(0xFFFFFFFF);
      _addRect(
        Rect.fromLTWH(margin, _cursorY, _contentWidth, rowHeight),
        fillColor: rowBg,
        strokeColor: const Color(0xFFE2E8F0),
        strokeWidth: 0.6,
      );
      _addTextLine(
        text: entry.key,
        left: margin + 10,
        top: _cursorY + 5.5,
        fontSize: 9.8,
        color: const Color(0xFF475569),
        isBold: true,
      );
      _addTextLine(
        text: entry.value,
        left: margin + 155,
        top: _cursorY + 5.5,
        fontSize: 9.8,
        color: const Color(0xFF0F172A),
      );
      _cursorY += rowHeight;
    }
    _cursorY += 6;
  }

  /// Adds a formatted data table with a colored header row, alternating rows,
  /// and optional proportional [columnWeights].
  void addTable({
    required List<String> headers,
    required List<List<String>> rows,
    Color headerColor = const Color(0xFF0F172A),
    List<double>? columnWeights,
  }) {
    if (headers.isEmpty) {
      return;
    }
    final int colCount = headers.length;
    final List<double> weights =
        (columnWeights != null && columnWeights.length == colCount)
            ? columnWeights
            : List<double>.filled(colCount, 1.0);
    final double totalWeight =
        weights.fold<double>(0.0, (double a, double b) => a + b);
    final List<double> colWidths = weights
        .map((double w) => _contentWidth * (w / totalWeight))
        .toList(growable: false);
    final List<double> colOffsets = <double>[margin];
    for (int c = 0; c < colCount - 1; c++) {
      colOffsets.add(colOffsets.last + colWidths[c]);
    }
    const double headerHeight = 26.0;
    const double rowHeight = 24.0;

    _addRect(
      Rect.fromLTWH(margin, _cursorY, _contentWidth, headerHeight),
      fillColor: headerColor,
      cornerRadius: 4,
    );
    for (int c = 0; c < colCount; c++) {
      _addTextLine(
        text: headers[c],
        left: colOffsets[c] + 8,
        top: _cursorY + 7,
        fontSize: 9.5,
        color: const Color(0xFFFFFFFF),
        isBold: true,
      );
    }
    _cursorY += headerHeight;

    for (int r = 0; r < rows.length; r++) {
      final List<String> row = rows[r];
      final Color bg =
          r.isEven ? const Color(0xFFF8FAFC) : const Color(0xFFFFFFFF);
      _addRect(
        Rect.fromLTWH(margin, _cursorY, _contentWidth, rowHeight),
        fillColor: bg,
        strokeColor: const Color(0xFFE2E8F0),
        strokeWidth: 0.6,
      );
      for (int c = 0; c < math.min(colCount, row.length); c++) {
        _addTextLine(
          text: row[c],
          left: colOffsets[c] + 8,
          top: _cursorY + 6,
          fontSize: 9.1,
          color: c == 0 ? const Color(0xFF0F172A) : const Color(0xFF334155),
          isBold: c == 0,
        );
      }
      _cursorY += rowHeight;
    }
    _cursorY += 6;
  }

  /// Adds a horizontal vector bar chart with labels and percentage bars.
  void addBarChart({
    required String title,
    required Map<String, double> values,
    Color barColor = const Color(0xFF0284C7),
  }) {
    _addTextLine(
      text: title,
      left: margin,
      top: _cursorY,
      fontSize: 11.2,
      color: const Color(0xFF0F172A),
      isBold: true,
    );
    _cursorY += 20;

    final double maxVal = values.values.fold<double>(
      100.0,
      (double prev, double el) => el > prev ? el : prev,
    );
    const double labelWidth = 130.0;
    final double trackWidth = _contentWidth - labelWidth - 50;

    for (final MapEntry<String, double> entry in values.entries) {
      _addTextLine(
        text: entry.key,
        left: margin,
        top: _cursorY + 2,
        fontSize: 9.6,
        color: const Color(0xFF334155),
      );
      _addRect(
        Rect.fromLTWH(margin + labelWidth, _cursorY, trackWidth, 14),
        fillColor: const Color(0xFFE2E8F0),
        cornerRadius: 5,
      );
      final double fillRatio = (entry.value / maxVal).clamp(0.0, 1.0);
      _addRect(
        Rect.fromLTWH(
          margin + labelWidth,
          _cursorY,
          trackWidth * fillRatio,
          14,
        ),
        fillColor: barColor,
        cornerRadius: 5,
      );
      _addTextLine(
        text: '${entry.value.toStringAsFixed(0)}%',
        left: margin + labelWidth + trackWidth + 8,
        top: _cursorY + 2,
        fontSize: 9.5,
        color: const Color(0xFF0F172A),
        isBold: true,
      );
      _cursorY += 22;
    }
    _cursorY += 4;
  }

  /// Adds a horizontal divider line across the content area.
  void addDivider({
    Color color = const Color(0xFFCBD5E1),
    double thickness = 1.0,
  }) {
    final Offset start = Offset(margin, _cursorY);
    final Offset end = Offset(width - margin, _cursorY);
    _elements.add(
      PdfLineElement(
        start: start,
        end: end,
        color: color,
        strokeWidth: thickness,
      ),
    );
    final String r = (color.r).toStringAsFixed(3);
    final String g = (color.g).toStringAsFixed(3);
    final String b = (color.b).toStringAsFixed(3);
    final String yPdf = _toPdfY(_cursorY).toStringAsFixed(2);
    _stream.writeln(
      '$r $g $b RG ${thickness.toStringAsFixed(2)} w '
      '${margin.toStringAsFixed(2)} $yPdf m '
      '${(width - margin).toStringAsFixed(2)} $yPdf l S',
    );
    _cursorY += thickness + 4;
  }

  /// Adds a page footer anchored near the bottom margin.
  void addFooter({
    required String leftText,
    required String rightText,
  }) {
    final double footerY = height - margin + 8;
    _elements.add(
      PdfLineElement(
        start: Offset(margin, footerY - 8),
        end: Offset(width - margin, footerY - 8),
        color: const Color(0xFFE2E8F0),
        strokeWidth: 0.8,
      ),
    );
    _addTextLine(
      text: leftText,
      left: margin,
      top: footerY,
      fontSize: 8.8,
      color: const Color(0xFF64748B),
    );
    final double rightWidth = rightText.length * 8.8 * 0.54;
    _addTextLine(
      text: rightText,
      left: width - margin - rightWidth,
      top: footerY,
      fontSize: 8.8,
