  /// Adds a new page to the document using a [PdfPageBuilder] callback.
  void addPage({
    double width = 595.28,
    double height = 841.89,
    String? bookmarkTitle,
    required void Function(PdfPageBuilder page) build,
  }) {
    final int pageNum = _pages.length + 1;
    final PdfPageBuilder pageBuilder = PdfPageBuilder(
      pageNumber: pageNum,
      width: width,
      height: height,
    );
    build(pageBuilder);
    _pages.add(
      _BuiltPageRecord(
        pageData: pageBuilder.toPageData(),
        contentStream: pageBuilder.toPdfContentStream(),
        bookmarkTitle: bookmarkTitle,
      ),
    );
  }

  /// Builds the [PdfDocument] along with its serialized `%PDF-1.7` byte payload.
  PdfDocument build({bool compressStreams = false}) {
    final Uint8List pdfBytes = toPdfBytes(compressStreams: compressStreams);
    final List<PdfPageData> pageList =
        _pages.map((_BuiltPageRecord r) => r.pageData).toList(growable: false);
    final List<PdfBookmark> bookmarks = <PdfBookmark>[];

    for (int i = 0; i < _pages.length; i++) {
      final String? bmTitle = _pages[i].bookmarkTitle;
      if (bmTitle != null && bmTitle.isNotEmpty) {
        bookmarks.add(
          PdfBookmark(
            id: 'bm_${i + 1}',
            title: bmTitle,
            pageNumber: i + 1,
          ),
        );
      }
    }

    return PdfDocument(
      pages: pageList,
      bookmarks: bookmarks,
      rawBytes: pdfBytes,
      metadata: PdfMetadata(
        title: title,
        author: author,
        subject: subject,
        keywords: keywords,
        creator: creator,
        producer: producer,
        creationDate: DateTime.utc(2026, 1, 1),
        modificationDate: DateTime.utc(2026, 1, 1),
        version: '1.7',
        fileSizeInBytes: pdfBytes.length,
      ),
    );
  }

  /// Serializes the built document into a valid `%PDF-1.7` byte buffer.
  Uint8List toPdfBytes({bool compressStreams = false}) {
    final BytesBuilder out = BytesBuilder(copy: false);
    final List<int> xrefOffsets = <int>[0]; // Object 0 is free

    void writeAscii(String text) {
      out.add(latin1.encode(text));
    }

    int startObject(int id) {
      final int offset = out.length;
      while (xrefOffsets.length <= id) {
        xrefOffsets.add(0);
      }
      xrefOffsets[id] = offset;
      writeAscii('$id 0 obj\n');
      return offset;
    }

    void endObject() {
      writeAscii('endobj\n');
    }

    writeAscii('%PDF-1.7\n');

    // Object 1: Catalog
    // Object 2: Pages
    // Object 3: Info
    // Object 4: Font F1 (Helvetica)
    // Object 5: Font F2 (Helvetica-Bold)
    final int pageCount = _pages.length;
    const int firstPageObjId = 6;

    startObject(1);
    writeAscii('<< /Type /Catalog /Pages 2 0 R >>\n');
    endObject();

    final List<String> kidsRefs = <String>[];
    for (int i = 0; i < pageCount; i++) {
      final int pageObjId = firstPageObjId + i * 2;
      kidsRefs.add('$pageObjId 0 R');
    }

    startObject(2);
    writeAscii(
      '<< /Type /Pages /Kids [ ${kidsRefs.join(' ')} ] /Count $pageCount >>\n',
    );
    endObject();

    startObject(3);
    writeAscii(
      '<< /Title ${_encodePdfTextOperand(title)} '
      '/Author ${_encodePdfTextOperand(author)} '
      '/Subject ${_encodePdfTextOperand(subject)} '
      '/Keywords ${_encodePdfTextOperand(keywords)} '
      '/Creator ${_encodePdfTextOperand(creator)} '
      '/Producer ${_encodePdfTextOperand(producer)} '
      '/CreationDate (D:20260101000000Z) >>\n',
    );
    endObject();

    startObject(4);
    writeAscii(
      '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\n',
    );
    endObject();

    startObject(5);
    writeAscii(
      '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>\n',
    );
    endObject();

    for (int i = 0; i < pageCount; i++) {
      final _BuiltPageRecord rec = _pages[i];
      final int pageObjId = firstPageObjId + i * 2;
      final int contentObjId = pageObjId + 1;
      final String wStr = rec.pageData.width.toStringAsFixed(2);
      final String hStr = rec.pageData.height.toStringAsFixed(2);

      startObject(pageObjId);
      writeAscii(
        '<< /Type /Page /Parent 2 0 R '
        '/MediaBox [ 0 0 $wStr $hStr ] '
        '/Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> '
        '/Contents $contentObjId 0 R >>\n',
      );
      endObject();

      final Uint8List rawStreamBytes =
          Uint8List.fromList(latin1.encode(rec.contentStream));
      final Uint8List payload = compressStreams
          ? ZlibDecoder.encodeZlibStored(rawStreamBytes)
          : rawStreamBytes;
      final String filterEntry = compressStreams ? ' /Filter /FlateDecode' : '';

      startObject(contentObjId);
      writeAscii('<< /Length ${payload.length}$filterEntry >>\nstream\n');
      out.add(payload);
      writeAscii('\nendstream\n');
      endObject();
    }

    // Optional Outline objects for bookmarks
    final int nextObjId = firstPageObjId + pageCount * 2;
    for (int i = 0; i < _pages.length; i++) {
      final String? bm = _pages[i].bookmarkTitle;
      if (bm != null && bm.isNotEmpty) {
        startObject(nextObjId + i);
        writeAscii(
          '<< /Title ${_encodePdfTextOperand(bm)} /PageNumber ${i + 1} >>\n',
        );
        endObject();
      }
    }

    final int xrefStart = out.length;
    final int totalObjects = xrefOffsets.length;
    writeAscii('xref\n0 $totalObjects\n');
    writeAscii('0000000000 65535 f \n');
    for (int id = 1; id < totalObjects; id++) {
      final String padded = xrefOffsets[id].toString().padLeft(10, '0');
      writeAscii('$padded 00000 n \n');
    }
    writeAscii(
      'trailer\n<< /Size $totalObjects /Root 1 0 R /Info 3 0 R >>\n'
      'startxref\n$xrefStart\n%%EOF\n',
    );

    return out.takeBytes();
  }

  static String _encodePdfTextOperand(String input) {
    final bool hasNonAscii = input.codeUnits.any((int cu) => cu > 127);
    if (!hasNonAscii) {
      final String escaped = input
          .replaceAll(r'\', r'\\')
          .replaceAll('(', r'\(')
          .replaceAll(')', r'\)');
      return '($escaped)';
    }
    final StringBuffer hex = StringBuffer('FEFF');
    for (final int cu in input.codeUnits) {
      final int hi = (cu >> 8) & 0xFF;
      final int lo = cu & 0xFF;
      hex.write(hi.toRadixString(16).padLeft(2, '0').toUpperCase());
      hex.write(lo.toRadixString(16).padLeft(2, '0').toUpperCase());
    }
    return '<$hex>';
  }
}

/// Page layout builder used inside [PdfDocumentBuilder.addPage].
class PdfPageBuilder {
  /// Creates a [PdfPageBuilder] for the given [pageNumber] and dimensions.
  PdfPageBuilder({
    required this.pageNumber,
    this.width = 595.28,
    this.height = 841.89,
    this.margin = 44.0,
  }) : _cursorY = margin;

  /// 1-based page number.
  final int pageNumber;

  /// Page width in points.
  final double width;

  /// Page height in points.
  final double height;

  /// Horizontal and vertical page margin in points.
  final double margin;

  double _cursorY;
  final List<PdfGraphicElement> _elements = <PdfGraphicElement>[];
  final StringBuffer _stream = StringBuffer();

  double get _contentWidth => width - margin * 2;
  double _toPdfY(double topY) => height - topY;

  /// Adds vertical whitespace of [points] height.
  void addSpacer([double points = 12.0]) {
    _cursorY += points;
  }

  /// Adds a full-width top banner header to the page.
  void addBannerHeader({
    required String title,
    String? subtitle,
    Color backgroundColor = const Color(0xFF0F172A),
    Color accentColor = const Color(0xFF38BDF8),
    Color textColor = const Color(0xFFFFFFFF),
  }) {
    final Rect bannerRect = Rect.fromLTWH(margin, _cursorY, _contentWidth, 68);
    _addRect(bannerRect, fillColor: backgroundColor, cornerRadius: 8);

    final Rect stripRect = Rect.fromLTWH(margin, _cursorY, 6, 68);
    _addRect(stripRect, fillColor: accentColor);

    _addTextLine(
      text: title,
      left: margin + 20,
      top: _cursorY + 14,
      fontSize: 18,
      color: textColor,
      isBold: true,
    );
    if (subtitle != null && subtitle.isNotEmpty) {
      _addTextLine(
        text: subtitle,
        left: margin + 20,
        top: _cursorY + 40,
        fontSize: 10,
        color: accentColor,
      );
    }
    _cursorY += 76;
  }

  /// Adds a section heading (`level` 1, 2, or 3).
  void addHeading(
    String text, {
    int level = 1,
    Color color = const Color(0xFF0F172A),
  }) {
    final double fontSize = switch (level) {
      1 => 17.0,
      2 => 13.5,
      _ => 11.5,
    };
    _cursorY += level == 1 ? 6.0 : 4.0;
    _addTextLine(
      text: text,
      left: margin,
      top: _cursorY,
      fontSize: fontSize,
      color: color,
      isBold: true,
    );
    _cursorY += fontSize * 1.45;
    if (level == 1) {
      addDivider(color: const Color(0xFFE2E8F0), thickness: 1.2);
      _cursorY += 6;
    }
  }

  /// Adds a word-wrapped paragraph of body text.
  void addParagraph(
    String text, {
    double fontSize = 10.8,
    Color color = const Color(0xFF334155),
  }) {
    final List<String> lines = _wrapText(text, _contentWidth, fontSize);
    for (final String line in lines) {
      _addTextLine(
        text: line,
        left: margin,
        top: _cursorY,
        fontSize: fontSize,
        color: color,
      );
      _cursorY += fontSize * 1.45;
    }
    _cursorY += 4;
  }

  /// Adds a highlighted callout box with a left accent border.
  void addCalloutBox({
    required String title,
    required String body,
    Color accentColor = const Color(0xFF2563EB),
    Color backgroundColor = const Color(0xFFEFF6FF),
  }) {
    final List<String> bodyLines = _wrapText(body, _contentWidth - 32, 10.2);
    final double boxHeight = 34.0 + bodyLines.length * 15.0 + 10.0;

    final Rect boxRect =
        Rect.fromLTWH(margin, _cursorY, _contentWidth, boxHeight);
    _addRect(
      boxRect,
      fillColor: backgroundColor,
      strokeColor: accentColor.withAlpha(70),
      cornerRadius: 6,
    );
    _addRect(
      Rect.fromLTWH(margin, _cursorY, 5, boxHeight),
      fillColor: accentColor,
    );

    _addTextLine(
      text: title,
      left: margin + 16,
      top: _cursorY + 10,
      fontSize: 11.5,
      color: accentColor,
      isBold: true,
    );

    double lineY = _cursorY + 29;
    for (final String line in bodyLines) {
      _addTextLine(
        text: line,
        left: margin + 16,
        top: lineY,
        fontSize: 10.2,
        color: const Color(0xFF1E293B),
      );
      lineY += 15.0;
    }

    _cursorY += boxHeight + 8;
  }

  /// Adds a two-column key-value summary grid.
  void addKeyValueGrid(Map<String, String> items) {
    final List<MapEntry<String, String>> entries = items.entries.toList();
    const double rowHeight = 24.0;
    for (int i = 0; i < entries.length; i++) {
      final MapEntry<String, String> entry = entries[i];
      final Color rowBg =
          i.isEven ? const Color(0xFFF8FAFC) : const Color(0xFFFFFFFF);
      _addRect(
        Rect.fromLTWH(margin, _cursorY, _contentWidth, rowHeight),
        fillColor: rowBg,
        strokeColor: const Color(0xFFE2E8F0),
        strokeWidth: 0.6,
      );
      _addTextLine(
        text: entry.key,
        left: margin + 10,
        top: _cursorY + 6,
        fontSize: 10.0,
        color: const Color(0xFF475569),
        isBold: true,
      );
      _addTextLine(
        text: entry.value,
        left: margin + 165,
        top: _cursorY + 6,
        fontSize: 10.0,
        color: const Color(0xFF0F172A),
      );
      _cursorY += rowHeight;
    }
    _cursorY += 6;
  }

  /// Adds a formatted data table with a colored header row and alternating rows.
  void addTable({
    required List<String> headers,
    required List<List<String>> rows,
    Color headerColor = const Color(0xFF1E293B),
  }) {
    if (headers.isEmpty) {
      return;
    }
    final int colCount = headers.length;
    final double colWidth = _contentWidth / colCount;
    const double headerHeight = 26.0;
    const double rowHeight = 24.0;

    // Header background
    _addRect(
      Rect.fromLTWH(margin, _cursorY, _contentWidth, headerHeight),
      fillColor: headerColor,
    );
    for (int c = 0; c < colCount; c++) {
      _addTextLine(
        text: headers[c],
        left: margin + c * colWidth + 8,
        top: _cursorY + 7,
        fontSize: 9.8,
        color: const Color(0xFFFFFFFF),
        isBold: true,
      );
    }
    _cursorY += headerHeight;

    for (int r = 0; r < rows.length; r++) {
      final List<String> row = rows[r];
      final Color bg =
          r.isEven ? const Color(0xFFF8FAFC) : const Color(0xFFFFFFFF);
      _addRect(
        Rect.fromLTWH(margin, _cursorY, _contentWidth, rowHeight),
        fillColor: bg,
        strokeColor: const Color(0xFFE2E8F0),
        strokeWidth: 0.6,
      );
      for (int c = 0; c < math.min(colCount, row.length); c++) {
        _addTextLine(
          text: row[c],
          left: margin + c * colWidth + 8,
          top: _cursorY + 6,
          fontSize: 9.5,
          color: const Color(0xFF334155),
        );
      }
      _cursorY += rowHeight;
    }
    _cursorY += 6;
  }

  /// Adds a horizontal vector bar chart with labels and percentage bars.
  void addBarChart({
    required String title,
    required Map<String, double> values,
    Color barColor = const Color(0xFF0284C7),
  }) {
    _addTextLine(
      text: title,
      left: margin,
      top: _cursorY,
      fontSize: 11.5,
      color: const Color(0xFF0F172A),
      isBold: true,
    );
    _cursorY += 20;

    final double maxVal = values.values.fold<double>(
      100.0,
      (double prev, double el) => el > prev ? el : prev,
    );
    const double labelWidth = 130.0;
    final double trackWidth = _contentWidth - labelWidth - 50;

    for (final MapEntry<String, double> entry in values.entries) {
      _addTextLine(
        text: entry.key,
        left: margin,
        top: _cursorY + 2,
        fontSize: 9.8,
        color: const Color(0xFF334155),
      );
      // Track background
      _addRect(
        Rect.fromLTWH(margin + labelWidth, _cursorY, trackWidth, 14),
        fillColor: const Color(0xFFE2E8F0),
        cornerRadius: 4,
      );
      final double fillRatio = (entry.value / maxVal).clamp(0.0, 1.0);
      _addRect(
        Rect.fromLTWH(
          margin + labelWidth,
          _cursorY,
          trackWidth * fillRatio,
          14,
        ),
        fillColor: barColor,
        cornerRadius: 4,
      );
      _addTextLine(
        text: '${entry.value.toStringAsFixed(0)}%',
        left: margin + labelWidth + trackWidth + 8,
        top: _cursorY + 2,
        fontSize: 9.5,
        color: const Color(0xFF0F172A),
        isBold: true,
      );
      _cursorY += 22;
    }
    _cursorY += 4;
  }

  /// Adds a horizontal divider line across the content area.
  void addDivider({
    Color color = const Color(0xFFCBD5E1),
    double thickness = 1.0,
  }) {
    final Offset start = Offset(margin, _cursorY);
    final Offset end = Offset(width - margin, _cursorY);
    _elements.add(
      PdfLineElement(
        start: start,
        end: end,
        color: color,
        strokeWidth: thickness,
      ),
    );
    final String r = (color.r).toStringAsFixed(3);
    final String g = (color.g).toStringAsFixed(3);
    final String b = (color.b).toStringAsFixed(3);
    final String yPdf = _toPdfY(_cursorY).toStringAsFixed(2);
    _stream.writeln(
      '$r $g $b RG ${thickness.toStringAsFixed(2)} w '
      '${margin.toStringAsFixed(2)} $yPdf m '
      '${(width - margin).toStringAsFixed(2)} $yPdf l S',
    );
    _cursorY += thickness + 4;
  }

  /// Adds a page footer anchored near the bottom margin.
  void addFooter({
    required String leftText,
    required String rightText,
  }) {
    final double footerY = height - margin + 8;
    _elements.add(
      PdfLineElement(
        start: Offset(margin, footerY - 8),
        end: Offset(width - margin, footerY - 8),
        color: const Color(0xFFE2E8F0),
        strokeWidth: 0.8,
      ),
    );
    _addTextLine(
      text: leftText,
      left: margin,
      top: footerY,
      fontSize: 9.0,
      color: const Color(0xFF64748B),
    );
    final double rightWidth = rightText.length * 9.0 * 0.52;
    _addTextLine(
      text: rightText,
      left: width - margin - rightWidth,
      top: footerY,
      fontSize: 9.0,
      color: const Color(0xFF64748B),
      isBold: true,
    );
  }

  void _addRect(
    Rect rect, {
    Color? fillColor,
    Color? strokeColor,
    double strokeWidth = 1.0,
    double cornerRadius = 0.0,
  }) {
    _elements.add(
      PdfRectElement(
        rect: rect,
        fillColor: fillColor,
        strokeColor: strokeColor,
        strokeWidth: strokeWidth,
        cornerRadius: cornerRadius,
      ),
    );

    final double pdfBottomY = _toPdfY(rect.bottom);
    if (fillColor != null) {
      final String r = fillColor.r.toStringAsFixed(3);
      final String g = fillColor.g.toStringAsFixed(3);
      final String b = fillColor.b.toStringAsFixed(3);
      _stream.write('$r $g $b rg ');
    }
    if (strokeColor != null) {
      final String r = strokeColor.r.toStringAsFixed(3);
      final String g = strokeColor.g.toStringAsFixed(3);
      final String b = strokeColor.b.toStringAsFixed(3);
      _stream.write('$r $g $b RG ${strokeWidth.toStringAsFixed(2)} w ');
    }
    final String op = (fillColor != null && strokeColor != null)
        ? 'B'
        : (fillColor != null ? 'f' : 'S');
    _stream.writeln(
      '${rect.left.toStringAsFixed(2)} ${pdfBottomY.toStringAsFixed(2)} '
      '${rect.width.toStringAsFixed(2)} ${rect.height.toStringAsFixed(2)} re $op',
    );
  }

  void _addTextLine({
    required String text,
    required double left,
    required double top,
    required double fontSize,
    required Color color,
    bool isBold = false,
  }) {
    final double factor = isBold ? 0.56 : 0.52;
    final double estWidth = math.max(8.0, text.length * fontSize * factor);
    final double estHeight = fontSize * 1.25;

    _elements.add(
      PdfTextElement(
        text: text,
        bounds: Rect.fromLTWH(left, top, estWidth, estHeight),
        fontSize: fontSize,
        color: color,
        fontFamily: isBold ? 'F2' : 'F1',
        isBold: isBold,
      ),
    );

    final String r = color.r.toStringAsFixed(3);
    final String g = color.g.toStringAsFixed(3);
    final String b = color.b.toStringAsFixed(3);
    final String fontKey = isBold ? 'F2' : 'F1';
    final double baselinePdfY = _toPdfY(top + fontSize);
    final String operand = PdfDocumentBuilder._encodePdfTextOperand(text);
    _stream.writeln(
      'BT /$fontKey ${fontSize.toStringAsFixed(1)} Tf '
      '$r $g $b rg '
      '${left.toStringAsFixed(2)} ${baselinePdfY.toStringAsFixed(2)} Td '
      '$operand Tj ET',
    );
  }

  static List<String> _wrapText(
    String text,
    double maxWidth,
    double fontSize,
  ) {
    final List<String> lines = <String>[];
    final int maxCharsPerLine =
        math.max(20, (maxWidth / (fontSize * 0.51)).floor());

    for (final String paragraph in text.split('\n')) {
      final List<String> words = paragraph.split(RegExp(r'\s+'));
      final StringBuffer currentLine = StringBuffer();
      for (final String word in words) {
        if (word.isEmpty) {
          continue;
        }
        if (currentLine.isEmpty) {
          currentLine.write(word);
        } else if (currentLine.length + 1 + word.length <= maxCharsPerLine) {
          currentLine.write(' $word');
        } else {
          lines.add(currentLine.toString());
          currentLine
            ..clear()
            ..write(word);
        }
      }
      if (currentLine.isNotEmpty) {
        lines.add(currentLine.toString());
      }
    }
    return lines;
  }

  /// Builds the [PdfPageData] model for this page.
  PdfPageData toPageData() {
    return PdfPageData(
      pageNumber: pageNumber,
      width: width,
      height: height,
      elements: List<PdfGraphicElement>.unmodifiable(_elements),
    );
  }

  /// Returns the raw PDF content stream commands generated for this page.
  String toPdfContentStream() => _stream.toString();
}

class _BuiltPageRecord {
  const _BuiltPageRecord({
    required this.pageData,
    required this.contentStream,
    this.bookmarkTitle,
  });

  final PdfPageData pageData;
  final String contentStream;
  final String? bookmarkTitle;
}
